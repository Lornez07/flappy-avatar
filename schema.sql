 * VITE_SUPABASE_ANON_KEY=your-anon-key
 *
 * IMPORTANT — trust model:
 * The client keeps its own copy of the avatar as a small data URL and submits it
 * inline with the score, so no storage bucket is required. Avatars are capped at
 * 64 KB by a CHECK constraint to stop the table being used as blob storage.
 *
 * A public leaderboard with anonymous inserts is tamper-prone by nature: a
 * determined player can always POST a fake score straight to the REST API. The
 * constraints and trigger below raise the cost of casual cheating but they are
 * NOT a trust boundary. If scores ever carry stakes, validate them server-side
 * (Edge Function) and require authentication.
 */

-- ============================================================================
-- LEADERBOARD TABLE
-- ============================================================================

CREATE TABLE IF NOT EXISTS leaderboards (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  player_name TEXT NOT NULL,
  score INT NOT NULL DEFAULT 0,
  -- Small inline data URL for the avatar, or a public URL. Never a blob store.
  avatar_url TEXT,
  CONSTRAINT valid_score CHECK (score >= 0 AND score <= 999999),
  CONSTRAINT valid_name_length CHECK (char_length(player_name) BETWEEN 1 AND 24),
  -- Reject padding and control characters.
  CONSTRAINT valid_name_chars CHECK (player_name = btrim(player_name)),
  CONSTRAINT avatar_max_size CHECK (avatar_url IS NULL OR octet_length(avatar_url) <= 65536)
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_leaderboards_score ON leaderboards(score DESC);
CREATE INDEX IF NOT EXISTS idx_leaderboards_player_name ON leaderboards(LOWER(player_name));
CREATE INDEX IF NOT EXISTS idx_leaderboards_created_at ON leaderboards(created_at DESC);

-- ============================================================================
-- ANTI-ABUSE TRIGGER
-- ============================================================================
-- Caps submissions per name so a single client cannot flood the board. This is a
-- speed bump, not a security control (see the trust-model note above).

CREATE OR REPLACE FUNCTION enforce_submission_rate_limit()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  recent_count INT;
BEGIN
  SELECT COUNT(*) INTO recent_count
  FROM leaderboards
  WHERE player_name = NEW.player_name
    AND created_at > CURRENT_TIMESTAMP - INTERVAL '1 minute';

  IF recent_count >= 5 THEN
    RAISE EXCEPTION 'Rate limit exceeded: max 5 submissions per name per minute'
      USING ERRCODE = 'check_violation';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_submission_rate_limit ON leaderboards;
CREATE TRIGGER trg_submission_rate_limit
  BEFORE INSERT ON leaderboards
  FOR EACH ROW
  EXECUTE FUNCTION enforce_submission_rate_limit();

-- ============================================================================
-- ROW LEVEL SECURITY (RLS)
-- ============================================================================

ALTER TABLE leaderboards ENABLE ROW LEVEL SECURITY;

-- Public read.
DROP POLICY IF EXISTS "leaderboards_read_all" ON leaderboards;
CREATE POLICY "leaderboards_read_all" ON leaderboards
  FOR SELECT USING (true);

-- Anonymous insert. Constraints + rate limit above do the sanity checking.
DROP POLICY IF EXISTS "leaderboards_insert_anonymous" ON leaderboards;
CREATE POLICY "leaderboards_insert_anonymous" ON leaderboards
  FOR INSERT WITH CHECK (true);

-- No UPDATE or DELETE policy: rows are append-only for anonymous clients.

-- ============================================================================
-- VIEWS (OPTIONAL)
-- ============================================================================

CREATE OR REPLACE VIEW leaderboard_top_100 AS
SELECT
  ROW_NUMBER() OVER (ORDER BY score DESC) AS rank,
  player_name,
  score,
  created_at
FROM leaderboards
ORDER BY score DESC
LIMIT 100;

CREATE OR REPLACE VIEW leaderboard_daily AS
SELECT
  ROW_NUMBER() OVER (ORDER BY score DESC) AS rank,
  player_name,
  score,
  created_at
FROM leaderboards
WHERE DATE(created_at) = CURRENT_DATE
ORDER BY score DESC;